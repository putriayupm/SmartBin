import 'dotenv/config';
import { pool } from './config/db.js';

const { rows: officers } = await pool.query(
  "SELECT user_id, assigned_zone FROM users WHERE role = 'officer'"
);

for (const o of officers) {
  const { rows: houses } = await pool.query(
    'SELECT household_id, current_fill_level FROM households WHERE zone = $1 ORDER BY current_fill_level DESC',
    [o.assigned_zone]
  );
  for (const [i, h] of houses.entries()) {
    await pool.query(
      `INSERT INTO schedules (schedule_date, household_id, officer_id, priority_score, route_order, reason)
       VALUES ((NOW() AT TIME ZONE 'Asia/Jakarta')::date, $1, $2, $3, $4, $5)
       ON CONFLICT (schedule_date, household_id) DO NOTHING`,
      [h.household_id, o.user_id, h.current_fill_level, i + 1,
       'Sample schedule for testing (not generated by the AI agent)']
    );
  }
}
console.log(`Sample schedules created for ${officers.length} zones`);
await pool.end();